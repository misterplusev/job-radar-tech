-- Additive delivery state; only the service role can access this queue.
-- No historical backfill: previously stored jobs are not mass-announced.
create table if not exists public.tech_job_notifications (
  id bigint generated by default as identity primary key,
  company text not null,
  job_url text not null,
  payload jsonb not null,
  state text not null default 'pending'
    check (state in ('pending', 'delivered', 'expired', 'inactive')),
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  discord_message_id text,
  unique (company, job_url)
);
alter table public.tech_job_notifications enable row level security;
revoke all on public.tech_job_notifications from anon, authenticated;
grant select, insert, update on public.tech_job_notifications to service_role;
grant usage, select on sequence public.tech_job_notifications_id_seq to service_role;
create index if not exists tech_job_notifications_pending_idx
  on public.tech_job_notifications (id) where state = 'pending';

NOTIFY pgrst, 'reload schema';
